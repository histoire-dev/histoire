it.each(['stale', 'busy'])('handles %s start rejection without admitting a second job', async (code) => {
  const { ready, button, request, channel, wrapper } = setup(cleanups)
  await ready()
  await button('Continue').trigger('click')
  await button('Install').trigger('click')
  channel.emit('histoire:ui:marketplace-job-state', { requestId: request('job-start').requestId, error: { code: code as 'stale' | 'busy', message: 'Project changed' } })
  await flushMicrotasks(6)
  if (code === 'stale') {
    channel.emit('histoire:ui:marketplace-plan-result', { requestId: request().requestId, plan: plan('2') })
    await flushMicrotasks(6)
    expect(wrapper.text()).toContain('Review updated changes')
    expect(wrapper.text()).toContain('+2 lines')
  }
  else {
    channel.emit('histoire:ui:marketplace-job-state', { requestId: request('job-current').requestId, job: job({ id: '@histoire/plugin-designs' }) })
    await flushMicrotasks(6)
    expect(wrapper.text()).toContain('@histoire/plugin-designs')
    expect(wrapper.text()).toContain('Packages: +1')
  }
})

