import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'pathe'
import { configDefaults, defineConfig } from 'vitest/config'

const currentDir = dirname(fileURLToPath(import.meta.url))
/** CLI package sources: specs share module instances with the CLI's own test utilities. */
const cliSrc = resolve(currentDir, '../histoire-cli/src')

export default defineConfig({
  resolve: {
    alias: [
      // Unit specs run against the CLI sources (like its own specs), so the spec utilities
      // imported from the CLI package and the code under test are the same module instances.
      { find: /^@histoire\/cli\/protocol\/(.*)$/, replacement: `${cliSrc}/terminal/protocol/$1.ts` },
      { find: /^@histoire\/cli\/sanitize$/, replacement: `${cliSrc}/terminal/output/sanitize.ts` },
      { find: /^@histoire\/cli\/workbench-url$/, replacement: `${cliSrc}/workbench-url.ts` },
      { find: /^@histoire\/cli$/, replacement: `${cliSrc}/index.ts` },
      // Several specs exercise the app-side stores of `@histoire/app`, which
      // import `vue`. Vue is only installed in that package, so a spec driving
      // their reactivity needs an explicit path to the very entry the stores
      // themselves resolve (one shared Vue instance).
      { find: 'vue', replacement: resolve(currentDir, '../histoire-app/node_modules/vue/index.mjs') },
      // Real compatibility-store tests share this Pinia dependency and the
      // same Vue alias as app sources, without importing vendor-bundled Vue.
      { find: 'pinia', replacement: resolve(currentDir, '../histoire-vendors/node_modules/pinia/dist/pinia.mjs') },
      // App sources resolve Vue Router through Vite's vendor alias. Mirror it
      // here so route-adapter specs exercise the same bundled dependency.
      { find: 'vue-router', replacement: '@histoire/vendors/vue-router' },
      // Those app modules also read the user config, which only exists as a
      // virtual module generated by the Vite plugin at dev/build time.
      { find: 'virtual:$histoire-config', replacement: resolve(currentDir, 'src/node/__tests__/utils/histoire-config-stub.ts') },
      // Vue story host specs import setup files generated from the user config.
      { find: 'virtual:$histoire-setup', replacement: resolve(currentDir, 'src/node/__tests__/utils/histoire-setup-stub.ts') },
      { find: 'virtual:$histoire-generated-global-setup', replacement: resolve(currentDir, 'src/node/__tests__/utils/histoire-generated-setup-stub.ts') },
    ],
  },
  test: {
    exclude: [...configDefaults.exclude, '**/mcp/integration/**', '**/terminal/integration/**', '**/embed/integration/**', '**/embed/consumers/**', '**/mcp/package-smoke.spec.ts', '**/tailwind/integration/**'],
    testTimeout: 15_000,
  },
})
