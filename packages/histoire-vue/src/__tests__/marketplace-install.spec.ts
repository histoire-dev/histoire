it('replans options after 200 ms, hides dependencies and rejects superseded replies', async () => {
  vi.useFakeTimers()
  const { ready, wrapper, request, channel, button } = setup(cleanups)
  await ready()
  expect(wrapper.text()).toContain('+1 lines')
  expect(wrapper.find('[role="group"][aria-label="Fail tests on"]').exists()).toBe(false)
  await wrapper.get('input[role="switch"]').setValue(true)
  expect(wrapper.get('[role="group"][aria-label="Fail tests on"]').text()).toContain('Critical')
  expect(wrapper.text()).toContain('Fail tests on')
  expect(button('Continue').attributes('disabled')).toBeDefined()
  await vi.advanceTimersByTimeAsync(199)
  expect(channel.sent.filter(item => item.event.endsWith('-plan'))).toHaveLength(1)
  await vi.advanceTimersByTimeAsync(1)
  expect(request().request.options.test).toBe(true)
  const old = request().requestId
  await wrapper.get('input[role="switch"]').setValue(false)
  await vi.advanceTimersByTimeAsync(200)
  expect(request().request.options).not.toHaveProperty('failOn')
  channel.emit('histoire:ui:marketplace-plan-result', { requestId: request().requestId, plan: plan('3') })
  channel.emit('histoire:ui:marketplace-plan-result', { requestId: old, plan: plan('2') })
  await flushMicrotasks(6)
  expect(wrapper.text()).toContain('+3 lines')
  expect(wrapper.text()).not.toContain('HstA11y({ test: true })')
  expect(wrapper.find('[role="group"][aria-label="Fail tests on"]').exists()).toBe(false)
})

